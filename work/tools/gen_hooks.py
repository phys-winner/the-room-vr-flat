#!/usr/bin/env python3
"""Generate src/roomfix/gen_symbols.h from src/roomfix/symbols.spec.

Spec lines (comments start with #):
  HOOK <ID> <MethodName>[|<signature substring>]   inline hook target (needs >=16 bytes, no branch into the stolen prologue)
  CALL <ID> <MethodName>[|<signature substring>]   function we call directly (8-byte preimage verified at runtime)
  META <ID> <ScriptMetadata/ScriptMetadataMethod/ScriptString name>   address of a metadata global slot
  FIELD <ID> <hex offset>                         plain constant (documented offsets)
Everything is resolved against the immutable decoded_original libil2cpp.so and Il2CppDumper output;
the build-id of that binary is emitted and checked at runtime before any patch is written.
"""
import bisect
import json
import re
import sys
from pathlib import Path

from capstone import CS_ARCH_ARM64, CS_MODE_ARM, Cs
from elftools.elf.elffile import ELFFile

ROOT = Path(__file__).resolve().parents[2]
LIB = ROOT / "decoded_original" / "lib" / "arm64-v8a" / "libil2cpp.so"
SCRIPT = ROOT / "work" / "il2cppdumper" / "script.json"
SPEC = ROOT / "src" / "roomfix" / "symbols.spec"
OUT = ROOT / "src" / "roomfix" / "gen_symbols.h"


def build_id(elf):
    for sec in elf.iter_sections():
        if sec.name == ".note.gnu.build-id":
            for note in sec.iter_notes():
                return note["n_desc"]
    raise SystemExit("no build-id")


def main():
    if not SCRIPT.is_file() or not LIB.is_file():
        # a checkout without the Il2CppDumper output builds from the committed header (the library checks the
        # build-id and every preimage at run time anyway)
        print(f"gen_hooks: {SCRIPT.relative_to(ROOT)} or the decoded libil2cpp.so missing - keeping {OUT.name}")
        return
    data = LIB.read_bytes()
    elf = ELFFile(open(LIB, "rb"))
    segs = [(s["p_vaddr"], s["p_offset"], s["p_filesz"]) for s in elf.iter_segments() if s["p_type"] == "PT_LOAD"]

    def v2o(va):
        for v, o, sz in segs:
            if v <= va < v + sz:
                return va - v + o
        raise SystemExit(f"address {va:#x} outside PT_LOAD")

    d = json.loads(SCRIPT.read_text(encoding="utf-8"))
    methods = d["ScriptMethod"]
    starts = sorted(set(m["Address"] for m in methods) | set(d.get("Addresses", [])))
    metas = {}
    for key in ("ScriptMetadata", "ScriptMetadataMethod"):
        for m in d[key]:
            metas.setdefault(m["Name"], m["Address"])
    for m in d["ScriptString"]:
        metas.setdefault("str:" + m["Value"], m["Address"])

    md = Cs(CS_ARCH_ARM64, CS_MODE_ARM)
    md.detail = False
    hooks, calls, defs = [], [], []
    for lineno, raw in enumerate(SPEC.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.split("#", 1)[0].strip() if not raw.strip().startswith("META") else raw.strip()
        if not line or line.startswith("#"):
            continue
        kind, ident, rest = line.split(None, 2)
        if kind == "FIELD":
            defs.append(f"#define {ident} {rest}")
            continue
        if kind == "META":
            if rest not in metas:
                raise SystemExit(f"line {lineno}: metadata not found: {rest}")
            defs.append(f"#define META_{ident} 0x{metas[rest]:x}UL /* {rest} */")
            continue
        name, _, sig = rest.partition("|")
        if name.startswith("0x"):
            # runtime (non-managed) function: address from manual analysis, size given after '|'
            addr = int(name, 16)
            size = int(sig, 0) if sig else 0
            name = f"il2cpp-runtime@{addr:#x}"
        else:
            cand = [m for m in methods if m["Name"] == name and (not sig or sig in m["Signature"])]
            addrs = sorted(set(m["Address"] for m in cand))
            if len(addrs) != 1:
                raise SystemExit(f"line {lineno}: {name}|{sig}: {len(addrs)} matches {[hex(a) for a in addrs]}")
            addr = addrs[0]
            i = bisect.bisect_right(starts, addr)
            size = (starts[i] - addr) if i < len(starts) else 0x1000
        off = v2o(addr)
        if kind == "HOOK":
            if size < 16:
                raise SystemExit(f"line {lineno}: {name} is only {size} bytes; hook a caller instead")
            body = data[off:off + size]
            for ins in md.disasm(body, addr):
                if ins.mnemonic in ("b", "bl", "cbz", "cbnz", "tbz", "tbnz") or ins.mnemonic.startswith("b."):
                    tgt = int(ins.op_str.split("#")[-1], 16)
                    if addr < tgt < addr + 16:
                        raise SystemExit(f"line {lineno}: {name} branches into its own prologue ({ins.address:#x})")
            pre = data[off:off + 16]
            hooks.append((ident, name, addr, pre, size))
        elif kind == "CALL":
            calls.append((ident, name, addr, data[off:off + 8]))
        else:
            raise SystemExit(f"line {lineno}: unknown kind {kind}")

    bid = build_id(elf)
    out = ["/* generated by work/tools/gen_hooks.py from src/roomfix/symbols.spec - do not edit */",
           "#pragma once", "#include <stdint.h>",
           f'#define RF_IL2CPP_BUILD_ID "{bid}"', ""]
    out.append("enum {")
    for ident, *_ in hooks:
        out.append(f"    H_{ident},")
    out.append("    H_COUNT\n};")
    out.append("static const struct rf_hook_desc { const char* name; uintptr_t rva; uint8_t pre[16]; } g_hook_desc[H_COUNT] = {")
    for ident, name, addr, pre, size in hooks:
        b = ", ".join(f"0x{x:02x}" for x in pre)
        out.append(f'    [H_{ident}] = {{"{name}", 0x{addr:x}, {{{b}}}}}, /* {size} bytes */')
    out.append("};\n")
    out.append("enum {")
    for ident, *_ in calls:
        out.append(f"    C_{ident},")
    out.append("    C_COUNT\n};")
    out.append("static const struct rf_call_desc { const char* name; uintptr_t rva; uint8_t pre[8]; } g_call_desc[C_COUNT] = {")
    for ident, name, addr, pre in calls:
        b = ", ".join(f"0x{x:02x}" for x in pre)
        out.append(f'    [C_{ident}] = {{"{name}", 0x{addr:x}, {{{b}}}}},')
    out.append("};\n")
    out.extend(defs)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}: {len(hooks)} hooks, {len(calls)} calls, {len(defs)} defines, build-id {bid}")


if __name__ == "__main__":
    main()
