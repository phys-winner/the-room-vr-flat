#!/usr/bin/env python3
"""Generate src/roomfix/gen_port_strings.h from src/roomfix/port_strings.json.

Every glyph of a translation (and of its upper-case form, menus force upper case) must already occur in the
game's own dictionary for that language, so the language's TextMesh Pro font can draw it. The dictionaries are
read from work/loc/<Language>.txt; when missing they are extracted from decoded_original with UnityPy.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src" / "roomfix" / "port_strings.json"
OUT = ROOT / "src" / "roomfix" / "gen_port_strings.h"
LOC = ROOT / "work" / "loc"
DATA = ROOT / "decoded_original" / "assets" / "bin" / "Data"


def extract_dictionaries(names):
    import UnityPy  # noqa: PLC0415
    LOC.mkdir(parents=True, exist_ok=True)
    for f in DATA.iterdir():
        if f.stat().st_size > 400_000:
            continue
        try:
            env = UnityPy.load(str(f))
        except Exception:
            continue
        for o in env.objects:
            if o.type.name != "TextAsset":
                continue
            d = o.read()
            if d.m_Name in names:
                data = d.m_Script
                if isinstance(data, str):
                    data = data.encode("utf-8", "surrogateescape")
                (LOC / f"{d.m_Name}.txt").write_bytes(data)


def c_escape(s):
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c == "\n":
            out.append("\\n")
        elif c in '"\\':
            out.append("\\" + c)
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def main():
    spec = json.loads(SRC.read_text(encoding="utf-8"))
    langs = spec["languages"]
    if any(not (LOC / f"{l}.txt").exists() for l in langs):
        extract_dictionaries(set(langs))
    glyphs = {l: set((LOC / f"{l}.txt").read_text(encoding="utf-8")) for l in langs}
    errors = []
    entries = []
    for key, tr in spec["strings"].items():
        texts = []
        for l in langs:
            if l not in tr:
                errors.append(f"{key}: missing {l}")
                texts.append("")
                continue
            t = tr[l].replace("\\n", "\n")
            # menu labels and values are drawn upper-case (LocaliseText.ForceUppercase); tutorial texts as written
            for ch in set(t + (t.upper() if key.startswith("PORT_") else "")):
                if ch == "\n" or (ch.isascii() and ch.isprintable()):
                    continue
                if ch not in glyphs[l]:
                    errors.append(f"{key} [{l}]: glyph {ch!r} U+{ord(ch):04X} not in the game's {l} dictionary")
            texts.append(t)
        for k in [key, *tr.get("_also", [])]:
            entries.append((k, texts))
    if errors:
        print("\n".join(errors))
        raise SystemExit(f"{len(errors)} problem(s)")
    first = "".join(sorted({k[0] for k, _ in entries}))
    lines = ["// Generated by work/tools/gen_strings.py from port_strings.json - do not edit.", "#pragma once",
             f"#define RF_NLANG {len(langs)}",
             f"#define RF_PORT_KEY_FIRST {c_escape(first)}  /* first letters of all keys: cheap filter */",
             "static const char* const RF_LANG_NAMES[RF_NLANG] = {" + ", ".join(c_escape(l) for l in langs) + "};",
             "static const struct { const char* key; const char* text[RF_NLANG]; } RF_PORT_STRINGS[] = {"]
    for k, texts in entries:
        lines.append("    {" + c_escape(k) + ", {")
        for t in texts:
            lines.append("        " + c_escape(t) + ",")
        lines.append("    }},")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}: {len(entries)} keys x {len(langs)} languages, all glyphs present in the game's dictionaries")


if __name__ == "__main__":
    sys.exit(main())
